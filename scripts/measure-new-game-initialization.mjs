import { chromium } from '@playwright/test';
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';
const server=await createServer({server:{host:'127.0.0.1',port:5173,strictPort:true}});await server.listen();
const label = process.argv[2] || 'current';
const outputDir=resolve(process.argv[3] || 'test-results/initialization-measurements');mkdirSync(outputDir,{recursive:true});
const browser = await chromium.launch({ headless:true });
const runs=[];
for(const rate of [1,6]) for(let repeat=0;repeat<3;repeat++) {
  const page=await browser.newPage();
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setCPUThrottlingRate',{rate});
  await page.goto('http://127.0.0.1:5173');
  await page.getByRole('button',{name:'読売ジャイアンツ',exact:true}).waitFor();
  const phases=await page.evaluate(async()=>{
    const taskEntries=[];const observer=new PerformanceObserver(list=>taskEntries.push(...list.getEntries()));observer.observe({type:"longtask",buffered:false});
    await new Promise(resolve=>requestAnimationFrame(()=>setTimeout(resolve,0)));
    const bootstrap=await import('/baseball-manager/src/engine/bootstrapTeams.js');
    const career=await import('/baseball-manager/src/engine/careerStats.js');
    const save=await import('/baseball-manager/src/engine/saveload.js');
    let seed=20261009; const original=Math.random; Math.random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296;};
    const start=performance.now();
    const teams=bootstrap.createInitialTeamsAsync ? await bootstrap.createInitialTeamsAsync() : bootstrap.createInitialTeams();
    const generated=performance.now();
    const entries=career.collectCareerLogsForIndexedDb(teams);
    const result=await save.initializeCareerLogsInIndexedDb(entries);
    const stored=performance.now(); Math.random=original;
    await new Promise(resolve=>requestAnimationFrame(()=>setTimeout(resolve,0))); observer.disconnect();
    if(!result.ok)throw Error('history save failed');
    window.initTasks=[];window.initObserver=new PerformanceObserver(list=>window.initTasks.push(...list.getEntries().map(e=>e.duration)));window.initObserver.observe({type:'longtask',buffered:false});
    return {generation:generated-start,maxGenerationTask:Math.max(0,...taskEntries.filter(e=>e.startTime>=start && e.startTime<generated).map(e=>e.duration)),history:stored-generated,players:teams.flatMap(t=>[...t.players,...t.farm]).length,historyRows:entries.reduce((n,e)=>n+e.careerEntries.length,0)};
  });
  await page.close();
  const homePage=await browser.newPage();
  const homeCdp=await homePage.context().newCDPSession(homePage);
  await homeCdp.send("Emulation.setCPUThrottlingRate",{rate});
  await homePage.addInitScript(()=>{window.initTasks=[];window.initObserver=new PerformanceObserver(list=>window.initTasks.push(...list.getEntries().map(e=>e.duration)));window.initObserver.observe({type:"longtask",buffered:false});});
  await homePage.goto("http://127.0.0.1:5173");
  await homePage.getByRole("button",{name:"読売ジャイアンツ",exact:true}).waitFor();
  await homePage.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>setTimeout(()=>{window.initTasks=[];window.initObserver.takeRecords();resolve();},0))));
  await homeCdp.send('Profiler.enable');await homeCdp.send('Profiler.start');
  const start=Date.now();await homePage.getByRole('button',{name:'読売ジャイアンツ',exact:true}).click();
  await homePage.locator('.topbar').filter({hasText:'読売ジャイアンツ'}).waitFor({timeout:20000});
  const home=Date.now()-start;
  const {profile}=await homeCdp.send('Profiler.stop');
  writeFileSync(`${outputDir}/${label}-cpu-${rate}-${repeat}.json`,JSON.stringify(profile));
  const tasks=await homePage.evaluate(()=>window.initTasks);
  runs.push({rate,repeat,...phases,home,maxLongTask:Math.max(0,...tasks)});
  await homePage.close();
}
await browser.close();await server.close();writeFileSync(`${outputDir}/${label}-measurements.json`,JSON.stringify(runs,null,2));console.log(JSON.stringify(runs,null,2));
